#!/usr/bin/env node

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docsRegistryPath = join(
  repoRoot,
  'projects/www/src/app/routes/docs/data/component-docs.registry.ts',
);
const sourceRoot = join(repoRoot, 'projects/duxkit-ai/src/lib');
const outputPath = join(
  repoRoot,
  'projects/www/src/app/routes/docs/data/component-api-metadata.generated.ts',
);

const docsRegistrySource = readFileSync(docsRegistryPath, 'utf8');
const docsRegistryFile = ts.createSourceFile(
  docsRegistryPath,
  docsRegistrySource,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TS,
);
const slugs = readComponentDocSlugs(docsRegistryFile);
const sourceFiles = slugs.flatMap((slug) => readComponentSourceFiles(slug));
const program = ts.createProgram(sourceFiles, {
  experimentalDecorators: true,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  paths: { 'duxkit-ai/*': [join(sourceRoot, '*.entrypoint.ts')] },
  module: ts.ModuleKind.Preserve,
  target: ts.ScriptTarget.ES2022,
});
const checker = program.getTypeChecker();

const componentApiMetadata = Object.fromEntries(
  slugs.map((slug) => [slug, buildComponentMetadata(slug)]),
);

const output = `// Generated by pnpm docs:generate-metadata. Do not edit by hand.
import { type ComponentDocSlug } from './component-docs.registry';

export interface ComponentApiInputMetadata {
  readonly name: string;
  readonly type: string;
  readonly defaultValue: string;
  readonly required: boolean;
  readonly description?: string;
}

export interface ComponentApiOutputMetadata {
  readonly name: string;
  readonly type: string;
  readonly description?: string;
}

export interface ComponentApiSymbolMetadata {
  readonly name: string;
  readonly selectors: readonly string[];
  readonly exportAs?: string;
  readonly inputs: readonly ComponentApiInputMetadata[];
  readonly outputs: readonly ComponentApiOutputMetadata[];
  readonly sourcePath: string;
}

export interface ComponentApiMetadata {
  readonly selectors: readonly string[];
  readonly exports: readonly string[];
  readonly inputs: readonly string[];
  readonly outputs: readonly string[];
  readonly sourcePaths: readonly string[];
  readonly symbols: readonly ComponentApiSymbolMetadata[];
}

export const componentApiMetadata = ${formatObject(componentApiMetadata)} satisfies Record<ComponentDocSlug, ComponentApiMetadata>;
`;

const prettierOptions = (await resolveConfig(outputPath)) ?? {};
writeFileSync(outputPath, await format(output, { ...prettierOptions, filepath: outputPath }));
console.log(`Generated ${relative(repoRoot, outputPath)}`);

function readComponentDocSlugs(sourceFile) {
  const slugs = [];

  visit(sourceFile);

  return slugs;

  function visit(node) {
    if (ts.isPropertyAssignment(node) && propertyNameText(node.name) === 'slug') {
      const value = literalText(node.initializer);

      if (value) {
        slugs.push(value);
      }
    }

    ts.forEachChild(node, visit);
  }
}

function readComponentSourceFiles(slug) {
  const directory = join(sourceRoot, slug);
  const entries = readdirSync(directory, { withFileTypes: true });

  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => join(directory, entry.name))
    .filter((filePath) => {
      const name = filePath.split('/').at(-1) ?? '';
      return name.endsWith('.ts') && !name.endsWith('.spec.ts') && !name.endsWith('.stories.ts');
    })
    .sort((a, b) => sourceFileSortKey(slug, a).localeCompare(sourceFileSortKey(slug, b)));
}

function sourceFileSortKey(slug, filePath) {
  const fileName = filePath.split('/').at(-1) ?? '';
  const baseName = fileName.replace(/\.ts$/, '');

  if (baseName === slug) {
    return `0-${fileName}`;
  }

  if (baseName === `${slug}-content`) {
    return `1-${fileName}`;
  }

  if (baseName === `${slug}-trigger`) {
    return `2-${fileName}`;
  }

  return `3-${fileName}`;
}

function buildComponentMetadata(slug) {
  const symbols = readComponentSourceFiles(slug).flatMap((filePath) => {
    const sourceFile = program.getSourceFile(filePath);

    if (!sourceFile) {
      return [];
    }

    return readAngularSymbols(sourceFile);
  });

  return {
    selectors: unique(symbols.flatMap((symbol) => symbol.selectors)),
    exports: unique(symbols.map((symbol) => symbol.name)),
    inputs: unique(symbols.flatMap((symbol) => symbol.inputs.map((input) => input.name))),
    outputs: unique(symbols.flatMap((symbol) => symbol.outputs.map((output) => output.name))),
    sourcePaths: unique(symbols.map((symbol) => symbol.sourcePath)),
    symbols,
  };
}

function readAngularSymbols(sourceFile) {
  const symbols = [];

  visit(sourceFile);

  return symbols;

  function visit(node) {
    if (ts.isClassDeclaration(node) && node.name) {
      const decoratorMetadata = readAngularDecoratorMetadata(node);

      if (decoratorMetadata) {
        symbols.push({
          name: node.name.text,
          selectors: splitSelectors(decoratorMetadata.selector),
          ...(decoratorMetadata.exportAs ? { exportAs: decoratorMetadata.exportAs } : {}),
          inputs: readClassMembers(node).flatMap(readInputMetadata),
          outputs: readClassMembers(node).flatMap(readOutputMetadata),
          sourcePath: relative(repoRoot, sourceFile.fileName),
        });
      }
    }

    ts.forEachChild(node, visit);
  }
}

function readClassMembers(node) {
  return checker
    .getTypeAtLocation(node)
    .getProperties()
    .flatMap((symbol) => (symbol.valueDeclaration ? [symbol.valueDeclaration] : []));
}

function readAngularDecoratorMetadata(node) {
  for (const decorator of ts.canHaveDecorators(node) ? (ts.getDecorators(node) ?? []) : []) {
    const expression = decorator.expression;

    if (!ts.isCallExpression(expression) || !ts.isIdentifier(expression.expression)) {
      continue;
    }

    if (expression.expression.text !== 'Component' && expression.expression.text !== 'Directive') {
      continue;
    }

    const [metadata] = expression.arguments;

    if (!metadata || !ts.isObjectLiteralExpression(metadata)) {
      continue;
    }

    const selector = readStringProperty(metadata, 'selector');

    if (!selector) {
      continue;
    }

    return {
      selector,
      exportAs: readStringProperty(metadata, 'exportAs'),
    };
  }

  return undefined;
}

function readInputMetadata(member) {
  if (!ts.isPropertyDeclaration(member) || !member.name || !member.initializer) {
    return [];
  }

  const inputCall = readInputCall(member.initializer);

  if (!inputCall) {
    return [];
  }

  return [
    {
      name: inputCall.alias ?? propertyNameText(member.name),
      type: inputCall.type,
      defaultValue: inputCall.required ? '-' : readDefaultValue(inputCall.defaultValue),
      required: inputCall.required,
      ...optionalDescription(member),
    },
  ];
}

function readOutputMetadata(member) {
  if (!ts.isPropertyDeclaration(member) || !member.name || !member.initializer) {
    return [];
  }

  const outputCall = readOutputCall(member.initializer, propertyNameText(member.name));

  if (!outputCall) {
    return [];
  }

  return [
    {
      name: outputCall.name,
      type: outputCall.type,
      ...optionalDescription(member),
    },
  ];
}

function readInputCall(expression) {
  const modelCall = readModelCall(expression);

  if (modelCall) {
    return modelCall;
  }

  if (!ts.isCallExpression(expression)) {
    return undefined;
  }

  if (ts.isIdentifier(expression.expression) && expression.expression.text === 'input') {
    return {
      alias: readAliasOption(expression.arguments[1]),
      defaultValue: expression.arguments[0],
      required: false,
      type: readValueType(expression, expression.arguments[0]),
    };
  }

  if (
    ts.isPropertyAccessExpression(expression.expression) &&
    ts.isIdentifier(expression.expression.expression) &&
    expression.expression.expression.text === 'input' &&
    expression.expression.name.text === 'required'
  ) {
    return {
      alias: readAliasOption(expression.arguments[0]),
      defaultValue: undefined,
      required: true,
      type: readValueType(expression, undefined),
    };
  }

  return undefined;
}

function readOutputCall(expression, memberName) {
  if (
    ts.isCallExpression(expression) &&
    ts.isIdentifier(expression.expression) &&
    expression.expression.text === 'output'
  ) {
    return {
      name: readAliasOption(expression.arguments[0]) ?? memberName,
      type: readValueType(expression, undefined),
    };
  }

  const modelCall = readModelCall(expression);

  if (!modelCall) {
    return undefined;
  }

  return {
    name: `${modelCall.alias ?? memberName}Change`,
    type: modelCall.type,
    description: modelCall.description,
  };
}

function readModelCall(expression) {
  if (!ts.isCallExpression(expression)) {
    return undefined;
  }

  if (ts.isIdentifier(expression.expression) && expression.expression.text === 'model') {
    return {
      alias: readAliasOption(expression.arguments[1]),
      defaultValue: expression.arguments[0],
      required: false,
      type: readValueType(expression, expression.arguments[0]),
    };
  }

  if (
    ts.isPropertyAccessExpression(expression.expression) &&
    ts.isIdentifier(expression.expression.expression) &&
    expression.expression.expression.text === 'model' &&
    expression.expression.name.text === 'required'
  ) {
    return {
      alias: readAliasOption(expression.arguments[0]),
      defaultValue: undefined,
      required: true,
      type: readValueType(expression, undefined),
    };
  }

  return undefined;
}

function readValueType(callExpression, fallbackExpression) {
  const [typeArgument] = callExpression.typeArguments ?? [];

  if (typeArgument) {
    return typeArgument.getText();
  }

  if (!fallbackExpression) {
    return 'void';
  }

  const primitiveType = readPrimitiveDefaultType(fallbackExpression);

  if (primitiveType) {
    return primitiveType;
  }

  const type = checker.getTypeAtLocation(fallbackExpression);
  return checker.typeToString(type);
}

function readPrimitiveDefaultType(expression) {
  if (ts.isStringLiteralLike(expression)) {
    return 'string';
  }

  if (
    expression.kind === ts.SyntaxKind.TrueKeyword ||
    expression.kind === ts.SyntaxKind.FalseKeyword
  ) {
    return 'boolean';
  }

  if (ts.isNumericLiteral(expression)) {
    return 'number';
  }

  return undefined;
}

function readDefaultValue(expression) {
  if (!expression) {
    return 'undefined';
  }

  return expression.getText();
}

function optionalDescription(node) {
  const description = readJsDocDescription(node);
  return description ? { description } : {};
}

function readJsDocDescription(node) {
  for (const doc of ts.getJSDocCommentsAndTags(node)) {
    if (doc.kind !== ts.SyntaxKind.JSDoc) {
      continue;
    }

    const comment = doc.comment;

    if (typeof comment === 'string') {
      return normalizeJsDocText(comment);
    }

    if (Array.isArray(comment)) {
      return normalizeJsDocText(
        comment.map((part) => ('text' in part ? part.text : part.getText())).join(''),
      );
    }
  }

  return undefined;
}

function normalizeJsDocText(value) {
  return value.replace(/\s+/g, ' ').trim();
}

function readAliasOption(expression) {
  if (!expression || !ts.isObjectLiteralExpression(expression)) {
    return undefined;
  }

  return readStringProperty(expression, 'alias');
}

function readStringProperty(objectLiteral, name) {
  for (const property of objectLiteral.properties) {
    if (!ts.isPropertyAssignment(property) || propertyNameText(property.name) !== name) {
      continue;
    }

    return literalText(property.initializer);
  }

  return undefined;
}

function splitSelectors(selector) {
  return selector
    .split(',')
    .map((value) => value.trim())
    .filter(Boolean);
}

function propertyNameText(name) {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) {
    return name.text;
  }

  return name.getText();
}

function literalText(node) {
  if (ts.isStringLiteralLike(node)) {
    return node.text;
  }

  return undefined;
}

function unique(values) {
  return [...new Set(values)];
}

function formatObject(value) {
  return JSON.stringify(value, null, 2).replace(/"([A-Za-z_$][\w$]*)":/g, '$1:');
}
